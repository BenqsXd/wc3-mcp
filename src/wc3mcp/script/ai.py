def export(ai: wai.AIData, td: TriggerData) -> str:
    """The AI Editor's export of `ai` (CRLF line endings)."""
    g = _Gen(ai, td)
    text = (g.header() + g.globals() + g.utilities() + g.options() + g.conditions() + g.heroes() + g.building()
            + g.attacking() + g.main())
    return text.replace("\n", "\r\n")
